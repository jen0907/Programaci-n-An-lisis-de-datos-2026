# Escriba aquí su juego Adivina el número.

import random

numero_secreto = random.randint (1,20)
intentos = 0
while True:
        intento = int(input("Ingrese algún número del 1 al 20: "))
        print(f"Intento: {intento}")
        intentos += 1
        distancia = abs(intento - numero_secreto)
        if distancia == 0:
            print(f"¡Acerto! Adivinó en {intentos} intentos")
            print("¡FELICIDADES! Adivinó el número.")
            print("¡Se terminó el juego!")
            break
        elif distancia >= 1 and distancia <= 2:
          print("¡Está HIRVIENDO!")
        elif distancia >= 3 and distancia <= 5:
          print("¡Esta CALIENTE!")
        elif distancia >= 6 and distancia <= 10:
          print("¡Está TIBIO!")
        elif distancia > 10:
          print("¡Está FRÍO!")
        if intento < numero_secreto:
          print("El número secreto es mayor.")
        elif intento > numero_secreto:
          print("El numero secreto es menor.")

